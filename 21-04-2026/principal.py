#### operações com numeros
# +
# - 
# *
# /
# % -> resto
# ** -> exponencial

# +
valor1 = 10
valor2 = 10

soma = valor1 + valor2
print(soma)

# -
valor1 = 20
valor2 = 10

diferença = valor1 - valor2
print(diferença)

# *
valor1 = 15
valor2 = 20

multiplicar = valor1 * valor2
print(multiplicar)

# /
valor1 = 50
valor2 = 10

dividir = valor1 / valor2
print(dividir)

# %
valor1 = 30
valor2 = 25

percentagem = valor1 % valor2
print(percentagem)